% ==========================================
% REGLAS DE APOYO
% ==========================================

no_visitado(Pais, Visitados) :-
    \+ member(Pais, Visitados).

coincide_gusto(Pais, Gustos) :-
    pais(Pais, _, _, TipoPais, _, _),
    member(TipoPais, Gustos).

coincide_tipo_viaje(Pais, Tipo) :-
    pais(Pais, _, _, TipoPais, _, _),
    TipoPais = Tipo.

coincide_clima(Pais, Clima) :-
    pais(Pais, _, _, _, _, ClimaPais),
    ClimaPais = Clima.

clima_parecido(tropical, calido).
clima_parecido(calido, tropical).
clima_parecido(templado, frio).
clima_parecido(frio, templado).
clima_parecido(templado, calido).
clima_parecido(calido, templado).

coincide_clima_flexible(Pais, Clima) :-
    pais(Pais, _, _, _, _, ClimaPais),
    (ClimaPais = Clima ; clima_parecido(ClimaPais, Clima)).

presupuesto_cercano(bajo, medio).
presupuesto_cercano(medio, bajo).
presupuesto_cercano(medio, alto).
presupuesto_cercano(alto, medio).

coincide_presupuesto(Pais, Presupuesto) :-
    pais(Pais, _, _, _, CostoPais, _),
    CostoPais = Presupuesto.

coincide_presupuesto_flexible(Pais, Presupuesto) :-
    pais(Pais, _, _, _, CostoPais, _),
    (CostoPais = Presupuesto ; presupuesto_cercano(CostoPais, Presupuesto)).

% ==========================================
% RECOMENDACIONES POR NIVEL
% ==========================================

% Nivel 1: exacta
recomendacion_nivel_1(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    pais(Pais, _, _, _, _, _),
    no_visitado(Pais, Visitados),
    coincide_gusto(Pais, Gustos),
    coincide_presupuesto(Pais, Presupuesto),
    coincide_clima(Pais, Clima),
    coincide_tipo_viaje(Pais, Tipo).

% Nivel 2: presupuesto y clima flexibles
recomendacion_nivel_2(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    pais(Pais, _, _, _, _, _),
    no_visitado(Pais, Visitados),
    coincide_gusto(Pais, Gustos),
    coincide_presupuesto_flexible(Pais, Presupuesto),
    coincide_clima_flexible(Pais, Clima),
    coincide_tipo_viaje(Pais, Tipo),
    \+ recomendacion_nivel_1(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

% Nivel 3: coincide con gusto o tipo, y presupuesto flexible
recomendacion_nivel_3(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    pais(Pais, _, _, _, _, _),
    no_visitado(Pais, Visitados),
    (coincide_gusto(Pais, Gustos) ; coincide_tipo_viaje(Pais, Tipo)),
    coincide_presupuesto_flexible(Pais, Presupuesto),
    coincide_clima_flexible(Pais, Clima),
    \+ recomendacion_nivel_1(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo),
    \+ recomendacion_nivel_2(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

% Nivel 4: recomendación básica, solo evita visitados y prioriza gusto o tipo
recomendacion_nivel_4(Pais, Visitados, Gustos, _Presupuesto, _Clima, Tipo) :-
    pais(Pais, _, _, _, _, _),
    no_visitado(Pais, Visitados),
    (coincide_gusto(Pais, Gustos) ; coincide_tipo_viaje(Pais, Tipo)),
    \+ recomendacion_nivel_1(Pais, Visitados, Gustos, _Presupuesto, _Clima, Tipo),
    \+ recomendacion_nivel_2(Pais, Visitados, Gustos, _Presupuesto, _Clima, Tipo),
    \+ recomendacion_nivel_3(Pais, Visitados, Gustos, _Presupuesto, _Clima, Tipo).

% ==========================================
% REGLA GENERAL
% ==========================================

recomendacion_final(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    recomendacion_nivel_1(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

recomendacion_final(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    recomendacion_nivel_2(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

recomendacion_final(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    recomendacion_nivel_3(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

recomendacion_final(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo) :-
    recomendacion_nivel_4(Pais, Visitados, Gustos, Presupuesto, Clima, Tipo).

