% ==========================================
% RUTA SUGERIDA SIMPLE
% ==========================================

ruta_sugerida([P1, P2, P3]) :-
    pais(P1, C1, _, _, _, _),
    pais(P2, C2, _, _, _, _),
    pais(P3, C3, _, _, _, _),
    P1 \= P2,
    P2 \= P3,
    P1 \= P3,
    C1 \= C2,
    C2 \= C3,
    C1 \= C3.